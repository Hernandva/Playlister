#!/usr/bin/env python3
"""Generate the PlaylisterUI Swift tokens and color asset catalog from a Claude Design tokens.json.

Usage:
    python3 scripts/codegen/design_tokens.py <tokens.json> <path/to/Packages/PlaylisterUI>

Input: the `project/tokens.json` export of a Claude Design design system:
    color.themes / color.tokens[{name, value: "#hex" | {themeId: "#hex"|"rgba()"}}]
    type.families {key: css font stack} / type.groups[{family, styles[{name, fontSize, fontWeight}]}]
    spacing.tokens[{name, value: "16px"}] / radius.tokens[{name, value: "12px"}]

Output (overwritten on every run):
    Sources/PlaylisterUI/Tokens/DSPalette.swift, DSColor.swift, DSTypography.swift, DSSpacing.swift, DSRadius.swift
    Sources/PlaylisterUI/Resources/Colors.xcassets/<token>.colorset

Python 3.9+, standard library only.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

HEADER = (
    "// Generated by scripts/codegen/design_tokens.py from Packages/PlaylisterUI/tokens.json.\n"
    "// Do not edit by hand: update tokens.json and run the script again.\n"
)

SWIFT_KEYWORDS = {
    "default", "case", "class", "struct", "enum", "protocol", "extension", "func", "var", "let", "if",
    "else", "switch", "return", "import", "public", "private", "internal", "static", "self", "Self",
    "true", "false", "nil", "in", "is", "as", "do", "try", "throw", "repeat", "while", "for", "where",
}

# Semantic roles used by the components -> token names that may play that role, in priority order.
COLOR_ROLES: dict[str, list[str]] = {
    "background": ["background", "bg", "bg-night", "paper", "canvas", "surface-background", "page"],
    "surface": ["surface", "card", "surface-1", "elevated", "panel"],
    "textPrimary": ["text-primary", "text", "ink", "foreground", "fg", "on-surface", "on-background", "label"],
    "textSecondary": ["text-secondary", "ink-2", "text-muted", "muted", "foreground-muted", "secondary-label"],
    "accent": ["accent", "primary", "brand", "tint", "action", "magenta"],
    "onAccent": ["on-accent", "on-primary", "on-brand", "on-tint", "text-primary"],
    "fillSecondary": ["fill-secondary", "fill-quiet", "fill", "secondary", "surface-2"],
    "destructive": ["destructive", "danger", "error", "critical"],
    "onDestructive": ["on-destructive", "on-danger", "on-error", "bg-night"],
    "separator": ["separator", "border", "divider", "outline", "stroke", "hairline"],
}
COLOR_FALLBACKS = {
    "background": "Color.clear",
    "surface": "Color.gray.opacity(0.12)",
    "textPrimary": "Color.primary",
    "textSecondary": "Color.secondary",
    "accent": "Color.accentColor",
    "onAccent": "Color.white",
    "fillSecondary": "Color.gray.opacity(0.2)",
    "destructive": "Color.red",
    "onDestructive": "Color.white",
    "separator": "Color.gray.opacity(0.3)",
}

# Semantic font -> (candidate style names, SwiftUI text style it scales with, fallback)
FONT_ROLES: dict[str, tuple[list[str], str, str]] = {
    "largeTitle": (["large-title", "largetitle", "display", "display-large", "h1"], "largeTitle", ".largeTitle"),
    "title": (["title", "hero-title", "title-1", "title-2", "h2", "display-medium"], "title", ".title"),
    "headline": (["headline", "nav-title", "title-3", "h3", "subtitle"], "headline", ".headline"),
    "body": (["body", "body-regular", "paragraph", "text"], "body", ".body"),
    "bodyStrong": (["body-strong", "body-bold", "body-emphasis", "button", "label"], "body", ".body.weight(.semibold)"),
    "footnote": (["footnote", "small", "body-small", "subhead"], "footnote", ".footnote"),
    "caption": (["caption", "section-header", "overline", "caption-1"], "caption", ".caption"),
}

GENERIC_SYSTEM = {"system-ui", "-apple-system", "blinkmacsystemfont", "sans-serif", "ui-sans-serif", "sf pro",
                  "sf pro text", "sf pro display", "helvetica neue", "helvetica", "arial", "system"}
GENERIC_MONO = {"monospace", "ui-monospace", "sf mono", "menlo"}
GENERIC_SERIF = {"serif", "ui-serif", "new york"}
GENERIC_ROUNDED = {"ui-rounded", "sf pro rounded"}

WEIGHTS = {100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium",
           600: "semibold", 700: "bold", 800: "heavy", 900: "black"}


def swift_identifier(name: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", name) if p]
    if not parts:
        return "token"
    ident = parts[0][0].lower() + parts[0][1:] + "".join(p[0].upper() + p[1:] for p in parts[1:])
    if ident[0].isdigit():
        ident = "value" + ident
    if ident in SWIFT_KEYWORDS:
        ident = f"`{ident}`"
    return ident


def parse_px(value) -> float | None:
    if isinstance(value, (int, float)):
        return float(value)
    match = re.match(r"^\s*(-?\d+(?:\.\d+)?)\s*(px|pt)?\s*$", str(value))
    return float(match.group(1)) if match else None


def parse_color(value: str) -> tuple[float, float, float, float]:
    text = value.strip().lower()
    if text.startswith("#"):
        digits = text[1:]
        if len(digits) in (3, 4):
            digits = "".join(c * 2 for c in digits)
        if len(digits) == 6:
            digits += "ff"
        if len(digits) != 8:
            raise ValueError(f"Unsupported hex color: {value}")
        r, g, b, a = (int(digits[i:i + 2], 16) for i in range(0, 8, 2))
        return r / 255, g / 255, b / 255, a / 255
    match = re.match(r"^rgba?\(([^)]*)\)$", text)
    if match:
        parts = [p.strip() for p in re.split(r"[,\s/]+", match.group(1)) if p.strip()]
        r, g, b = (float(p.rstrip("%")) * (2.55 if p.endswith("%") else 1) for p in parts[:3])
        a = float(parts[3].rstrip("%")) / (100 if parts[3].endswith("%") else 1) if len(parts) > 3 else 1.0
        return r / 255, g / 255, b / 255, a
    raise ValueError(f"Unsupported color value: {value}")


def colorset_entry(rgba, dark: bool) -> dict:
    r, g, b, a = rgba
    entry = {
        "color": {
            "color-space": "srgb",
            "components": {"red": f"{r:.3f}", "green": f"{g:.3f}", "blue": f"{b:.3f}", "alpha": f"{a:.3f}"},
        },
        "idiom": "universal",
    }
    if dark:
        entry = {"appearances": [{"appearance": "luminosity", "value": "dark"}], **entry}
    return entry


def theme_ids(tokens: dict) -> tuple[str | None, str | None]:
    themes = [t.get("id", "") for t in tokens.get("color", {}).get("themes", [])]
    light = next((t for t in themes if "light" in t.lower()), themes[0] if themes else None)
    dark = next((t for t in themes if "dark" in t.lower()), None)
    return light, dark


def color_values(token: dict, light_id, dark_id) -> tuple[str, str | None]:
    value = token["value"]
    if isinstance(value, str):
        return value, None
    light = value.get(light_id) if light_id else None
    light = light or next(iter(value.values()))
    dark = value.get(dark_id) if dark_id else None
    return light, dark


def pick(names: list[str], candidates: list[str]) -> str | None:
    lowered = {n.lower(): n for n in names}
    for candidate in candidates:
        if candidate in lowered:
            return lowered[candidate]
    return None


def font_expression(family_stack: str, size: float, weight: int, text_style: str) -> str:
    first = family_stack.split(",")[0].strip().strip("\"'")
    swift_weight = WEIGHTS.get(int(round(weight / 100.0) * 100), "regular")
    key = first.lower()
    design = None
    if key in GENERIC_MONO:
        design = "monospaced"
    if key in GENERIC_SERIF:
        design = "serif"
    if key in GENERIC_ROUNDED:
        design = "rounded"
    if key in GENERIC_SYSTEM or design:
        design_arg = f", design: .{design}" if design else ""
        return f"Font.system(size: {size:g}, weight: .{swift_weight}{design_arg})"
    return f'Font.custom("{first}", size: {size:g}, relativeTo: .{text_style}).weight(.{swift_weight})'


def members(raw: dict[str, float], semantic: dict[str, float]) -> list[str]:
    """CGFloat constants for every token plus the semantic names; a token with a semantic name keeps its own value."""
    lines = [f"    public static let {name}: CGFloat = {value:g}" for name, value in raw.items()]
    lines += [f"    public static let {name}: CGFloat = {value:g}" for name, value in semantic.items() if name not in raw]
    return lines


def generate(tokens_path: Path, package_dir: Path) -> list[str]:
    tokens = json.loads(tokens_path.read_text(encoding="utf-8"))
    report: list[str] = []
    sources = package_dir / "Sources" / "PlaylisterUI"
    tokens_dir = sources / "Tokens"
    catalog = sources / "Resources" / "Colors.xcassets"
    tokens_dir.mkdir(parents=True, exist_ok=True)
    if catalog.exists():
        shutil.rmtree(catalog)
    catalog.mkdir(parents=True)
    (catalog / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")

    # Colors ---------------------------------------------------------------
    light_id, dark_id = theme_ids(tokens)
    color_tokens = tokens.get("color", {}).get("tokens", [])
    palette_lines = []
    names = []
    for token in color_tokens:
        name = token["name"]
        light, dark = color_values(token, light_id, dark_id)
        entries = [colorset_entry(parse_color(light), dark=False)]
        if dark:
            entries.append(colorset_entry(parse_color(dark), dark=True))
        colorset = catalog / f"{name}.colorset"
        colorset.mkdir()
        (colorset / "Contents.json").write_text(
            json.dumps({"colors": entries, "info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
        usage = token.get("usage", "").replace("\n", " ")
        if usage:
            palette_lines.append(f"    /// {usage}")
        palette_lines.append(f'    public static let {swift_identifier(name)} = Color("{name}", bundle: .module)')
        names.append(name)

    (tokens_dir / "DSPalette.swift").write_text(
        HEADER + "import SwiftUI\n\n/// Every color token of the design system, with light and dark values.\n"
        "public enum DSPalette {\n" + "\n".join(palette_lines) + "\n}\n")

    role_lines = []
    for role, candidates in COLOR_ROLES.items():
        match = pick(names, candidates)
        expr = f"DSPalette.{swift_identifier(match)}" if match else COLOR_FALLBACKS[role]
        report.append(f"DSColor.{role} <- {match or 'fallback ' + COLOR_FALLBACKS[role]}")
        role_lines.append(f"    public static let {role} = {expr}")
    (tokens_dir / "DSColor.swift").write_text(
        HEADER + "import SwiftUI\n\n/// Semantic colors used by the components.\npublic enum DSColor {\n"
        + "\n".join(role_lines) + "\n}\n")

    # Typography -------------------------------------------------------------
    type_section = tokens.get("type", {})
    families = type_section.get("families", {})
    styles: dict[str, tuple[str, float, int]] = {}
    for group in type_section.get("groups", []):
        stack = families.get(group.get("family", ""), group.get("family", "system-ui"))
        for style in group.get("styles", []):
            size = parse_px(style.get("fontSize")) or 17
            styles[style["name"]] = (stack, size, int(style.get("fontWeight", 400)))

    scale_lines = []
    for name, (stack, size, weight) in styles.items():
        scale_lines.append(f"    public static let {swift_identifier(name)} = {font_expression(stack, size, weight, 'body')}")
    font_lines = []
    for role, (candidates, text_style, fallback) in FONT_ROLES.items():
        match = pick(list(styles), candidates)
        if match:
            stack, size, weight = styles[match]
            expr = font_expression(stack, size, weight, text_style)
        else:
            expr = f"Font{fallback}"
        report.append(f"DSFont.{role} <- {match or 'fallback system ' + fallback}")
        font_lines.append(f"    public static let {role} = {expr}")
    (tokens_dir / "DSTypography.swift").write_text(
        HEADER + "import SwiftUI\n\n/// Every type style of the design system.\npublic enum DSTypeScale {\n"
        + ("\n".join(scale_lines) or "    // No type styles in tokens.json.")
        + "\n}\n\n/// Semantic fonts used by the components.\npublic enum DSFont {\n" + "\n".join(font_lines) + "\n}\n")

    # Spacing ------------------------------------------------------------------
    spacing = {t["name"]: parse_px(t["value"]) for t in tokens.get("spacing", {}).get("tokens", [])}
    spacing = {k: v for k, v in spacing.items() if v is not None}
    tap = next((v for k, v in spacing.items() if re.search(r"tap|touch|hit", k)), 44.0)
    scale = sorted({v for k, v in spacing.items() if not re.search(r"tap|touch|hit", k) and v > 0})
    defaults = [4.0, 8.0, 16.0, 24.0, 32.0]
    if len(scale) >= 5:
        semantic = [scale[0], scale[1], scale[len(scale) // 2], scale[-2], scale[-1]]
    else:
        semantic = defaults
        if scale:
            report.append("Spacing: fewer than 5 spacing tokens, semantic spacing uses defaults 4/8/16/24/32")
    spacing_lines = members({swift_identifier(k): v for k, v in spacing.items()},
                            dict(zip(["xSmall", "small", "medium", "large", "xLarge", "tapMin"], semantic + [tap])))
    report.append("DSSpacing xSmall/small/medium/large/xLarge = " + "/".join(f"{v:g}" for v in semantic)
                  + f", tapMin = {tap:g}")
    (tokens_dir / "DSSpacing.swift").write_text(
        HEADER + "import CoreGraphics\n\n/// Spacing tokens and the semantic spacing used by the components.\n"
        "public enum DSSpacing {\n" + "\n".join(spacing_lines) + "\n}\n")

    # Radius -------------------------------------------------------------------
    radius = {t["name"]: parse_px(t["value"]) for t in tokens.get("radius", {}).get("tokens", [])}
    radius = {k: v for k, v in radius.items() if v is not None}
    values = sorted(radius.values())

    def radius_for(pattern: str, default: float) -> float:
        found = next((v for k, v in radius.items() if re.search(pattern, k)), None)
        return found if found is not None else default

    median = values[len(values) // 2] if values else 12.0
    small = values[0] if values else 6.0
    control = radius_for(r"control|button", median)
    card = radius_for(r"card", radius_for(r"list|surface|container|panel", max(values) if values else 16.0))
    radius_lines = members({swift_identifier(k): v for k, v in radius.items()},
                           {"small": small, "control": control, "card": card})
    report.append(f"DSRadius small/control/card = {small:g}/{control:g}/{card:g}")
    (tokens_dir / "DSRadius.swift").write_text(
        HEADER + "import CoreGraphics\n\n/// Corner radius tokens and the semantic radii used by the components.\n"
        "public enum DSRadius {\n" + "\n".join(radius_lines) + "\n}\n")

    fonts = sorted({s[0].split(",")[0].strip().strip("\"'") for s in styles.values()})
    custom = [f for f in fonts if f.lower() not in GENERIC_SYSTEM | GENERIC_MONO | GENERIC_SERIF | GENERIC_ROUNDED]
    if custom:
        report.append("Custom fonts to bundle in the app: " + ", ".join(custom))
    report.append(f"{len(names)} color tokens, {len(styles)} type styles, {len(spacing)} spacing, {len(radius)} radius")
    return report


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    report = generate(Path(sys.argv[1]), Path(sys.argv[2]))
    print("\n".join(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
